"""Samples points from the Fior logo so the film can assemble it out of gold particles.

Usage: python3 fior-bannere/film/puncte_logo.py   ->  writes fior-bannere/film/logo-puncte.js
(The browser cannot read pixels of local images, so the points are precomputed here.)
"""
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).parent
POINT_COUNT = 2600

alpha = np.asarray(Image.open(HERE.parent / "imagini" / "logo-fior.png").getchannel("A"))
ys, xs = np.nonzero(alpha > 128)
rng = np.random.default_rng(11)
picked = rng.choice(len(xs), size=POINT_COUNT, replace=False)

height, width = alpha.shape
points = ",".join(f"[{xs[i] / width:.4f},{ys[i] / height:.4f}]" for i in picked)
(HERE / "logo-puncte.js").write_text(
    "// Generated by puncte_logo.py: points inside the logo, as fractions of its width and height.\n"
    f"const LOGO_POINTS = [{points}];\n",
    encoding="utf-8",
)
print(f"{POINT_COUNT} points")
