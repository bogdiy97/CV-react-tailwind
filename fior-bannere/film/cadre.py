"""Extracts the shots of the official Fior hero video as JPEG sequences for the films that use real footage.

Downloads https://fiordrinks.ro/wp-content/uploads/2025/04/hero-video.mp4 into film/sursa/ if it is missing,
then writes film/cadre/<shot>/NNNN.jpg and film/cadre/index.js (frame counts). Both folders are git-ignored.

The source is a 50 fps timeline; some shots are real 50 fps (step 1: played one frame per output frame they
become 0.6x slow motion at 30 fps) and some are 25 fps with doubled frames (step 2 keeps the unique ones).

Usage: python3 fior-bannere/film/cadre.py
"""
import json
import subprocess
import urllib.request
from pathlib import Path

HERE = Path(__file__).parent
SOURCE = HERE / "sursa" / "hero-video.mp4"
URL = "https://fiordrinks.ro/wp-content/uploads/2025/04/hero-video.mp4"
OUT = HERE / "cadre"

# name: (start s, end s, step)
SHOTS = {
    "usa": (0.10, 8.30, 1),         # she walks out of the wooden door, along the columns
    "trepte": (8.38, 14.38, 2),     # down the steps, the camera tilts up to her face
    "portret": (14.46, 18.12, 1),   # close-up: face next to the bottle
    "eticheta": (18.20, 21.30, 1),  # macro: the label tilting
    "pasi": (22.70, 26.06, 2),      # heels and the red dress, bottle in hand
    "palarie": (26.14, 31.00, 2),   # portrait under the black hat
    "masa": (31.08, 34.78, 1),      # at the table with two bottles
    "turnare": (34.86, 36.70, 2),   # macro: the liqueur pours into a glass
}


def main():
    if not SOURCE.exists():
        SOURCE.parent.mkdir(parents=True, exist_ok=True)
        print("downloading", URL)
        urllib.request.urlretrieve(URL, SOURCE)

    index = {}
    for name, (start, end, step) in SHOTS.items():
        folder = OUT / name
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.glob("*.jpg"):
            old.unlink()
        subprocess.run([
            "ffmpeg", "-y", "-loglevel", "error", "-ss", str(start), "-to", str(end), "-i", str(SOURCE),
            "-vf", f"select='not(mod(n\\,{step}))'", "-vsync", "vfr", "-q:v", "3", str(folder / "%04d.jpg"),
        ], check=True)
        index[name] = len(list(folder.glob("*.jpg")))
        print(f"{name}: {index[name]} frames")

    (OUT / "index.js").write_text(
        "// Generated by cadre.py: frame counts of the footage clips in this folder.\n"
        f"const CLIP_FRAMES = {json.dumps(index)};\n", encoding="utf-8")


if __name__ == "__main__":
    main()
